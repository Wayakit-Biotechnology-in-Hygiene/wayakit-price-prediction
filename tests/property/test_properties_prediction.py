"""Properties of ``generate_predictions`` in ``ml_model/3_predicted_prices.py``.

This is the most important business rule of the pipeline: the suggested price never drops below
the margin floor ``cost × 1.30`` and, with 3 or more competitor rows of its type, it is clamped
to the SKU's market band (F7a): at most the p75 per liter or per piece (of the similar-size rows
when there are enough) times its size, and at least the type's minimum unless its size is outside
the market's size range. The floor always wins. ``generate_predictions`` does no I/O (it only
writes to the log), so it is called directly with fake models and market rows generated by
Hypothesis:

- ``FakeModel.predict`` returns, in order, the price per liter or per piece generated for
  each product that goes through that model (it is called once per product).
- ``estimators_`` is a list of fake trees with ``predict``; only
  ``calculate_confidence`` uses it.

The generated products resemble the F1 ``wayakit_products_to_predict_odoo.csv``: volume in
liters or pieces, and products with neither set to 0 or empty (F1 has 26 like that; the cost
can be 0).
"""
import math

import numpy as np
import pandas as pd
import pytest
from hypothesis import example, given
from hypothesis import strategies as st

from tests.conftest import load_module

prediction = load_module("ml_model/3_predicted_prices.py")

pytestmark = pytest.mark.property

TYPES = ["T0", "T1", "T2", "T3"]
SUBINDUSTRIES = ["Home", "Pets"]
# Report column names come from production (`porcentaje_de_ganancia` is part of the CSV contract).
NUMERIC_COLUMNS = [
    "predicted_price", "predicted_price_per_unit", "porcentaje_de_ganancia", "model_confidence",
    "market_min_found", "market_max_found", "competitors_count", "market_median_found",
    "market_p75_found",
]
FLOOR_FACTOR = 1.30
CENT = 0.01  # rounding to the cent; the floor is rounded up, so up to a whole cent
MARKET_COLUMNS = ["type_of_product", "price_per_unit", "size"]


class FakeTree:
    def __init__(self, value):
        self.value = value

    def predict(self, X):
        return np.full(len(X), self.value)


class FakeModel:
    def __init__(self, prices, tree_values):
        self._prices = list(prices)
        self.estimators_ = [FakeTree(v) for v in tree_values]

    def predict(self, X):
        assert len(X) == 1, "generate_predictions predicts one product at a time"
        return np.array([self._prices.pop(0)])


positives = st.floats(min_value=0.01, max_value=1e4, allow_nan=False, allow_infinity=False)


@st.composite
def products(draw):
    measure_kind = draw(st.sampled_from(["volume", "pieces", "both", "none"]))
    volume = draw(st.floats(0.01, 1000)) if measure_kind in ("volume", "both") else draw(
        st.sampled_from([0.0, float("nan")])
    )
    if measure_kind in ("pieces", "both"):
        pieces = float(draw(st.integers(1, 1000)))
    else:
        pieces = draw(st.sampled_from([0.0, float("nan")]))
    return {
        "Product_ID": f"FP-{draw(st.integers(0, 999)):03d}",
        "Product_Name": "Test product",
        "type_of_product": draw(st.sampled_from(TYPES)),
        "subindustry": draw(st.sampled_from(SUBINDUSTRIES)),
        "industry": "Transportation",
        "generic_product_type": "Cleaner",
        "company": "Wayakit",
        "channel": "B2B",
        "Volume_Liters": volume,
        "Pack_quantity_Units": pieces,
        # Cost 0 exists in F1 (6 products); otherwise, at least 0.001 SAR (a subnormal
        # would make the percentage margin overflow to inf, which is not a real case).
        "Unit_cost_SAR": draw(st.one_of(st.just(0.0), st.floats(0.001, 1e4))),
        "model_price": draw(positives),  # price per liter or per piece returned by the model
    }


@st.composite
def market_rows(draw):
    """Market rows as 2_train_models.py saves them: per type, price per unit and size."""
    rows = []
    for product_type in draw(st.lists(st.sampled_from(TYPES), unique=True, max_size=len(TYPES))):
        for _ in range(draw(st.integers(1, 8))):
            rows.append((product_type, draw(st.floats(0.01, 1e3)), draw(st.floats(0.005, 1000))))
    return pd.DataFrame(rows, columns=MARKET_COLUMNS)


def _size(p):
    for column in ("Volume_Liters", "Pack_quantity_Units"):
        if pd.notna(p[column]) and p[column] > 0:
            return column, p[column]
    return None, 0.0


def _run(product_list, vol_market, unit_market, trees):
    vol_prices = [p["model_price"] for p in product_list if _size(p)[0] == "Volume_Liters"]
    unit_prices = [p["model_price"] for p in product_list if _size(p)[0] == "Pack_quantity_Units"]
    df = pd.DataFrame(product_list).drop(columns="model_price")
    return prediction.generate_predictions(
        df,
        FakeModel(vol_prices, trees),
        FakeModel(unit_prices, trees),
        ["volume_liters"],
        ["total_quantity"],
        vol_market,
        unit_market,
    )


def _band(product, vol_market, unit_market):
    """Independent oracle of the market band: (count, low, p75, size_min, size_max) or None."""
    column, size = _size(product)
    if column is None:
        return None
    market = vol_market if column == "Volume_Liters" else unit_market
    rows = market[market["type_of_product"] == product["type_of_product"]]
    if rows.empty:
        return None
    similar = rows[(rows["size"] * 2 >= size) & (rows["size"] <= size * 2)]
    used = similar if len(similar) >= 3 else rows
    return (len(rows), rows["price_per_unit"].min(), float(np.quantile(used["price_per_unit"], 0.75)),
            rows["size"].min(), rows["size"].max())


@given(
    product_list=st.lists(products(), min_size=1, max_size=6),
    vol_market=market_rows(),
    unit_market=market_rows(),
    trees=st.lists(positives, min_size=1, max_size=5),
)
def test_margin_floor_and_market_band(product_list, vol_market, unit_market, trees):
    report = _run(product_list, vol_market, unit_market, trees)

    assert len(report) == len(product_list)
    for column in NUMERIC_COLUMNS:
        assert np.isfinite(report[column].astype(float)).all(), f"NaN or infinity in {column}"

    for product, (_, row) in zip(product_list, report.iterrows()):
        cost = product["Unit_cost_SAR"]
        floor = cost * FLOOR_FACTOR
        price = row["predicted_price"]
        assert math.isfinite(price)
        # Margin floor (C17): never below cost × 1.30, not even by rounding.
        assert price >= floor - 1e-9 * max(1.0, floor), (product, row.to_dict())
        column, size = _size(product)
        assert bool(row["has_size"]) == (column is not None)
        band = _band(product, vol_market, unit_market)
        assert row["competitors_count"] == (band[0] if band else 0)
        if band is None:
            assert not row["clamped_to_market"] and not row["volume_outside_market"]
            continue
        count, low, p75, size_min, size_max = band
        # Nothing but the market minimum (or the floor) can raise the model price.
        assert price <= max(floor, product["model_price"] * size, low * size) + 0.01 + 1e-9 * max(1.0, price)
        assert bool(row["volume_outside_market"]) == (not size_min <= size <= size_max)
        tolerance = CENT + 1e-9 * max(1.0, low * size, p75 * size, floor)
        assert row["market_p75_found"] == pytest.approx(round(p75 * size, 2), abs=tolerance)
        if count >= 3:
            # Ceiling: the p75 x size at every size (the floor wins if it is higher).
            assert price <= max(p75 * size, floor) + tolerance, (product, row.to_dict())
            # Lifted to the minimum, except above the size range.
            if size <= size_max:
                assert price >= low * size - tolerance, (product, row.to_dict())
        else:
            assert not row["clamped_to_market"], (product, row.to_dict())
        in_band = (size > size_max or low <= product["model_price"]) and product["model_price"] <= p75
        if not row["volume_capped"] and (count < 3 or in_band):
            # Not clamped and not capped: max(model price, floor) to the cent.
            model_price = product["model_price"] * size
            assert abs(price - max(model_price, floor)) <= tolerance + 0.005, (product, row.to_dict())


@given(
    product_list=st.lists(products(), min_size=2, max_size=6),
    vol_market=market_rows(),
    trees=st.lists(positives, min_size=1, max_size=5),
)
def test_a_size_above_the_market_never_costs_more_per_unit_than_a_smaller_sibling(product_list, vol_market, trees):
    """F7a, acting on volume_outside_market: a SKU larger than every market row of its type costs,
    per liter, at most what a smaller sibling (same subindustry and type, inside the range) costs
    before the floor."""
    product_list = [dict(p) for p in product_list]  # never mutate Hypothesis' own data
    for p in product_list:  # volumetric only, so every product goes through one model
        p["Volume_Liters"] = p["Volume_Liters"] if pd.notna(p["Volume_Liters"]) and p["Volume_Liters"] > 0 else 1.0
        p["Unit_cost_SAR"] = 0.0  # no floor: the per-liter comparison is exact
    empty = pd.DataFrame(columns=MARKET_COLUMNS)
    report = _run(product_list, vol_market, empty, trees)
    per_liter = report["predicted_price"] / [p["Volume_Liters"] for p in product_list]
    for i, (big, big_row) in enumerate(zip(product_list, report.itertuples())):
        band = _band(big, vol_market, empty)
        if band is None or big["Volume_Liters"] <= band[4]:
            continue
        for j, small in enumerate(product_list):
            small_band = _band(small, vol_market, empty)
            if (j != i and small["type_of_product"] == big["type_of_product"]
                    and small["subindustry"] == big["subindustry"]
                    and small["Volume_Liters"] < big["Volume_Liters"]
                    and small_band is not None and small["Volume_Liters"] <= small_band[4]):
                # Both prices are rounded to the cent: half a cent of slack per liter on each side.
                slack = 0.005 / big["Volume_Liters"] + 0.005 / small["Volume_Liters"]
                assert per_liter[i] <= per_liter[j] * (1 + 1e-9) + slack, (big, small)


@given(price=st.floats(0, 1e6), cost=st.floats(0, 1e5))
@example(price=0.0, cost=10.003846)  # cost × 1.30 = 13.005 -> round gives 13.0, below the floor
def test_apply_margin_floor_is_never_below_the_floor_and_at_most_a_cent_above(price, cost):
    final = prediction.apply_margin_floor(price, cost)
    floor = cost * FLOOR_FACTOR
    assert final >= floor - 1e-9 * max(1.0, floor)  # float noise only (5034.900000000001 -> 5034.90)
    assert final <= max(price, floor) + 0.01 + 1e-9 * max(1.0, floor)
    assert final == round(final, 2)


def test_market_band_uses_similar_sizes_when_there_are_enough():
    rows = pd.DataFrame({"type_of_product": "T", "price_per_unit": [100.0, 10.0, 12.0, 14.0, 16.0],
                         "size": [0.05, 1.0, 1.0, 1.5, 0.6]})
    band = prediction.market_band(rows, 1.0)
    assert band["match"] == "size" and band["count"] == 5
    assert band["low"] == 10.0 and band["max"] == 100.0
    assert band["p75"] == pytest.approx(float(np.quantile([10.0, 12.0, 14.0, 16.0], 0.75)))
    assert (band["size_min"], band["size_max"]) == (0.05, 1.5)
    # Only 2 rows between 2 and 8 L: every row is used.
    band = prediction.market_band(rows, 4.0)
    assert band["match"] == "all"
    assert band["p75"] == pytest.approx(float(np.quantile([100.0, 10.0, 12.0, 14.0, 16.0], 0.75)))
    assert prediction.market_band(rows.iloc[:0], 1.0) is None


def test_product_without_measure_with_empty_pieces_gets_the_floor_and_no_size():
    """Was a strict xfail: a NaN Pack_quantity_Units broke the 'volume' column with int(NaN)."""
    product = {
        "Product_ID": "FP-001", "Product_Name": "Test product", "type_of_product": "T0",
        "subindustry": "Home", "industry": "Transportation", "generic_product_type": "Cleaner",
        "company": "Wayakit", "channel": "B2C", "Volume_Liters": 0.0,
        "Pack_quantity_Units": float("nan"), "Unit_cost_SAR": 10.0, "model_price": 1.0,
    }
    empty = pd.DataFrame(columns=MARKET_COLUMNS)
    report = _run([product], empty, empty, [1.0])
    row = report.iloc[0]
    assert row["predicted_price"] == 13.0 and row["volume"] == "0 units" and not row["has_size"]


def _product(product_id, liters, subindustry="Pets", product_type="T0", cost=0.0):
    return {"Product_ID": product_id, "Product_Name": product_id, "type_of_product": product_type,
            "subindustry": subindustry, "industry": "Pets care", "generic_product_type": "Cleaner",
            "company": "Wayakit", "channel": "B2C", "Volume_Liters": liters, "Pack_quantity_Units": 0.0,
            "Unit_cost_SAR": cost}


def test_four_liters_above_the_market_is_capped_at_the_sibling_price_and_never_lifted():
    """The F5 cause 1 shape: competitors up to ~3.8 L; Wayakit 0.7 L and 4 L of the same type.

    The 0.7 L SKU (model 100/L) is lifted to the market minimum, 150/L. The 4 L model price
    (200/L) is capped at that 0.7 L price per liter (150/L), and nothing lifts it because 4 L is
    above the market's size range.
    """
    market = pd.DataFrame({"type_of_product": "T0", "price_per_unit": [150.0, 300.0, 400.0, 500.0],
                           "size": [3.788, 0.5, 0.946, 1.0]})
    products = [_product("SMALL", 0.7), _product("BIG", 4.0)]
    df = pd.DataFrame(products)
    report = prediction.generate_predictions(
        df, FakeModel([100.0, 200.0], [1.0]), FakeModel([], [1.0]), ["volume_liters"], ["total_quantity"],
        market, pd.DataFrame(columns=MARKET_COLUMNS))
    small, big = report.iloc[0], report.iloc[1]
    # 0.7 L: inside the range, lifted to the minimum 150/L.
    assert small["predicted_price"] == pytest.approx(105.0) and small["clamped_to_market"]
    # 4 L: model 200/L, capped at the sibling's 150/L (after its clamp), never lifted.
    assert big["volume_outside_market"] and big["volume_capped"]
    assert big["predicted_price"] == pytest.approx(600.0)


def test_cap_ignores_siblings_of_another_subindustry_or_type():
    market = pd.DataFrame({"type_of_product": ["T0", "T0", "T0"], "price_per_unit": [10.0, 20.0, 30.0],
                           "size": [0.5, 1.0, 1.0]})
    products = [_product("OTHER-SUB", 0.7, subindustry="Home"), _product("OTHER-TYPE", 0.7, product_type="T1"),
                _product("BIG", 4.0)]
    report = prediction.generate_predictions(
        pd.DataFrame(products), FakeModel([5.0, 5.0, 25.0], [1.0]), FakeModel([], [1.0]),
        ["volume_liters"], ["total_quantity"], market, pd.DataFrame(columns=MARKET_COLUMNS))
    big = report.iloc[2]
    assert not big["volume_capped"] and big["predicted_price"] == pytest.approx(100.0)  # 25/L x 4 L


def test_only_a_sibling_inside_the_market_range_can_cap():
    """A smaller sibling that is itself above the market's size range never caps a larger SKU."""
    market = pd.DataFrame({"type_of_product": "T0", "price_per_unit": [50.0, 60.0, 70.0], "size": [0.5, 0.75, 1.0]})
    products = [_product("MID", 2.0), _product("BIG", 4.0)]
    report = prediction.generate_predictions(
        pd.DataFrame(products), FakeModel([10.0, 40.0], [1.0]), FakeModel([], [1.0]),
        ["volume_liters"], ["total_quantity"], market, pd.DataFrame(columns=MARKET_COLUMNS))
    mid, big = report.iloc[0], report.iloc[1]
    assert mid["volume_outside_market"] and big["volume_outside_market"]
    assert not big["volume_capped"] and big["predicted_price"] == pytest.approx(160.0)  # 40/L x 4 L
