"""Properties of ``generate_predictions`` in ``ml_model/3_predicted_prices.py``.

This is the most important business rule of the pipeline: the suggested price never drops below
the margin floor ``cost × 1.30`` and, with 3 or more competitors, it is clamped to the market range
(the floor always wins). ``generate_predictions`` does no I/O (it only writes to the log), so it is
called directly with fake models and market statistics generated by Hypothesis:

- ``FakeModel.predict`` returns, in order, the price per liter or per piece generated for
  each product that goes through that model (it is called once per product).
- ``estimators_`` is a list of fake trees with ``predict``; only
  ``calculate_confidence`` uses it.

The generated products resemble the F1 ``wayakit_products_to_predict_odoo.csv``: volume in
liters or pieces, and products with neither set to 0 (F1 has 26 like that; the cost can be 0).
"""
import math

import numpy as np
import pandas as pd
import pytest
from hypothesis import Phase, example, given, settings
from hypothesis import strategies as st

from tests.conftest import load_module

prediction = load_module("ml_model/3_predicted_prices.py")

pytestmark = pytest.mark.property

TYPES = ["T0", "T1", "T2", "T3"]
SUBINDUSTRIES = ["Home", "Automotive", "Pets", "Hotels", "Aviation"]
# Report column names come from production (`porcentaje_de_ganancia` is part of the CSV contract).
NUMERIC_COLUMNS = [
    "predicted_price", "predicted_price_per_unit", "porcentaje_de_ganancia", "model_confidence",
    "market_min_found", "market_max_found", "competitors_count",
]
FLOOR_FACTOR = 1.30


class FakeTree:
    def __init__(self, value):
        self.value = value

    def predict(self, X):
        return np.full(len(X), self.value)


class FakeModel:
    def __init__(self, prices, tree_values):
        self._prices = list(prices)
        self.estimators_ = [FakeTree(v) for v in tree_values]

    def predict(self, X):
        assert len(X) == 1, "generate_predictions predicts one product at a time"
        return np.array([self._prices.pop(0)])


positives = st.floats(min_value=0.01, max_value=1e4, allow_nan=False, allow_infinity=False)


@st.composite
def products(draw):
    measure_kind = draw(st.sampled_from(["volume", "pieces", "both", "none"]))
    volume = draw(st.floats(0.01, 1000)) if measure_kind in ("volume", "both") else draw(
        st.sampled_from([0.0, float("nan")])
    )
    if measure_kind in ("pieces", "both"):
        pieces = float(draw(st.integers(1, 1000)))
    elif measure_kind == "volume":
        pieces = draw(st.sampled_from([0.0, float("nan")]))
    else:
        pieces = 0.0  # neither volume nor pieces: Odoo sends 0 (the NaN case has its own test)
    return {
        "Product_ID": f"FP-{draw(st.integers(0, 999)):03d}",
        "Product_Name": "Test product",
        "type_of_product": draw(st.sampled_from(TYPES)),
        "subindustry": draw(st.sampled_from(SUBINDUSTRIES)),
        "industry": "Transportation",
        "generic_product_type": "Cleaner",
        "company": "Wayakit",
        "channel": "B2B",
        "Volume_Liters": volume,
        "Pack_quantity_Units": pieces,
        # Cost 0 exists in F1 (6 products); otherwise, at least 0.001 SAR (a subnormal
        # would make the percentage margin overflow to inf, which is not a real case).
        "Unit_cost_SAR": draw(st.one_of(st.just(0.0), st.floats(0.001, 1e4))),
        "model_price": draw(positives),  # price per liter or per piece returned by the model
    }


@st.composite
def market_stats(draw):
    rows = []
    for product_type in draw(st.lists(st.sampled_from(TYPES), unique=True, max_size=len(TYPES))):
        minimum = draw(st.floats(0.01, 1e3))
        vol_min = draw(st.floats(0, 100))
        rows.append(
            {
                "type_of_product": product_type,
                "market_min": minimum,
                "market_max": minimum + draw(st.floats(0, 1e3)),
                "competitor_count": draw(st.integers(0, 20)),
                "vol_min": vol_min,
                "vol_max": vol_min + draw(st.floats(0, 1000)),
            }
        )
    columns = ["type_of_product", "market_min", "market_max", "competitor_count", "vol_min", "vol_max"]
    return pd.DataFrame(rows, columns=columns)


def _is_volumetric(p):
    return pd.notna(p["Volume_Liters"]) and p["Volume_Liters"] > 0


def _is_per_piece(p):
    return pd.notna(p["Pack_quantity_Units"]) and p["Pack_quantity_Units"] > 0


def _run(product_list, stats_vol, stats_unit, trees):
    vol_prices = [p["model_price"] for p in product_list if _is_volumetric(p)]
    unit_prices = [p["model_price"] for p in product_list if not _is_volumetric(p) and _is_per_piece(p)]
    df = pd.DataFrame(product_list).drop(columns="model_price")
    report = prediction.generate_predictions(
        df,
        FakeModel(vol_prices, trees),
        FakeModel(unit_prices, trees),
        ["volume_liters"],
        ["total_quantity"],
        stats_vol,
        stats_unit,
    )
    return report


def _expected_market(product, stats_vol, stats_unit):
    """(quantity, competitors, total minimum, total maximum) as production computes them."""
    if _is_volumetric(product):
        quantity, stats = product["Volume_Liters"], stats_vol
    elif _is_per_piece(product):
        quantity, stats = product["Pack_quantity_Units"], stats_unit
    else:
        return None, 0, 0.0, 0.0
    row = stats[stats["type_of_product"] == product["type_of_product"]]
    if row.empty:
        return quantity, 0, 0.0, 0.0
    row = row.iloc[0]
    return quantity, int(row["competitor_count"]), row["market_min"] * quantity, row["market_max"] * quantity


@given(
    product_list=st.lists(products(), min_size=1, max_size=6),
    stats_vol=market_stats(),
    stats_unit=market_stats(),
    trees=st.lists(positives, min_size=1, max_size=5),
)
def test_margin_floor_and_clamp_to_market(product_list, stats_vol, stats_unit, trees):
    report = _run(product_list, stats_vol, stats_unit, trees)

    assert len(report) == len(product_list)
    for column in NUMERIC_COLUMNS:
        assert np.isfinite(report[column].astype(float)).all(), f"NaN or infinity in {column}"

    for product, (_, row) in zip(product_list, report.iterrows()):
        cost = product["Unit_cost_SAR"]
        floor = cost * FLOOR_FACTOR
        price = row["predicted_price"]
        assert math.isfinite(price)
        # Margin floor (C17): never below round(cost × 1.30, 2).
        assert price >= round(floor, 2) - 0.005, (product, row.to_dict())

        quantity, competitors, minimum, maximum = _expected_market(product, stats_vol, stats_unit)
        assert row["competitors_count"] == competitors
        tolerance = 0.005 + 1e-9 * max(1.0, abs(minimum), abs(maximum), abs(floor))
        if competitors >= 3:
            # Clamp to the market; the floor wins if it is above the maximum.
            assert minimum - tolerance <= price <= max(maximum, floor) + tolerance, (product, row.to_dict())
        else:
            assert not row["clamped_to_market"], (product, row.to_dict())
            # No clamp: max(model price, floor) to the cent. Half-a-cent tolerance
            # because production rounds a numpy float64 (0.015 -> 0.02) and Python rounds
            # its float using the exact representation (0.015 -> 0.01).
            model_price = product["model_price"] * quantity if quantity is not None else 0
            assert abs(price - max(model_price, floor)) <= tolerance, (product, row.to_dict())


@pytest.mark.xfail(
    strict=True,
    raises=ValueError,
    reason="Minor BUG: a product with neither volume nor pieces and an empty (NaN) Pack_quantity_Units "
    "breaks generate_predictions with ValueError in int(NaN) while building the 'volume' column. It does "
    "not happen in F1 (Odoo sends 0 for the 26 products without a measure), but a CSV with the empty "
    "cell would bring down the whole step 3 (finding for pi-dev)",
)
@settings(phases=[Phase.explicit])
@given(product_list=st.lists(products(), min_size=1, max_size=1))
@example(
    product_list=[
        {
            "Product_ID": "FP-001", "Product_Name": "Test product", "type_of_product": "T0",
            "subindustry": "Home", "industry": "Transportation", "generic_product_type": "Cleaner",
            "company": "Wayakit", "channel": "B2C", "Volume_Liters": 0.0,
            "Pack_quantity_Units": float("nan"), "Unit_cost_SAR": 10.0, "model_price": 1.0,
        }
    ]
)
def test_bug_product_without_measure_with_empty_pieces(product_list):
    empty = pd.DataFrame(
        columns=["type_of_product", "market_min", "market_max", "competitor_count", "vol_min", "vol_max"]
    )
    report = _run(product_list, empty, empty, [1.0])
    assert report["predicted_price"].iloc[0] == round(10.0 * FLOOR_FACTOR, 2)
